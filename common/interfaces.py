from typing import Protocol, Dict, Any, List, Optional
from common.models import CapabilitySpec, DiscoverQuery, Match, Claims

class IdentityAPI(Protocol):
    async def register_agent(self, name: Optional[str] = None) -> Dict[str, Any]: ...
    async def heartbeat(self, agent_id: str, token: str) -> Dict[str, Any]: ...
    async def verify_token(self, token: str) -> Claims: ...
    async def deactivate_agent(self, agent_id: str) -> None: ...
    async def get_agent(self, agent_id: str) -> Dict[str, Any]: ...
    async def list_agents(self) -> List[Dict[str, Any]]: ...
    async def health(self) -> Dict[str, Any]: ...

class RegistryAPI(Protocol):
    async def publish(self, token: str, agent_id: str, capability: CapabilitySpec, instance_id: str) -> None: ...
    async def renew(self, token: str, agent_id: str, load: float = 0.0) -> None: ...
    async def withdraw(self, token: str, agent_id: str, capability_id: str) -> None: ...
    async def discover(self, query: DiscoverQuery) -> List[Match]: ...
    async def merge(self, remote_state: dict) -> None: ...
    async def get_state(self) -> dict: ...
    async def health(self) -> Dict[str, Any]: ...

class BrokerAPI(Protocol):
    async def publish(self, queue: str, envelope: dict) -> str: ...
    async def consume(self, queue: str) -> Optional[Dict[str, Any]]: ...
    async def ack(self, queue: str, delivery_id: str) -> None: ...
    async def nack(self, queue: str, delivery_id: str) -> None: ...
    async def stats(self) -> Dict[str, Any]: ...
    async def health(self) -> Dict[str, Any]: ...

class OrchestratorAPI(Protocol):
    async def create_task(self, steps: Optional[List[dict]] = None, workflow: Optional[str] = None, input_data: Optional[dict] = None, flow_id: Optional[str] = None) -> str: ...
    async def get_task(self, task_id: str) -> dict: ...
    async def list_tasks(self, state: Optional[str] = None) -> List[dict]: ...
    async def cancel_task(self, task_id: str) -> None: ...
    async def health(self) -> Dict[str, Any]: ...